import re
from pathlib import Path

import pandas as pd
import pytest

ROOT = Path(__file__).resolve().parents[1]
NUMBER = re.compile(r"[-+]?\d[\d,]*\.?\d*%?")


def numbers(text: str) -> set[str]:
    return {m.group(0).lstrip("+-").rstrip(".,") for m in NUMBER.finditer(text)}


@pytest.mark.skipif(not (ROOT / "outputs" / "key_findings.csv").exists(), reason="run analysis/run_all.py first")
def test_every_number_in_the_readme_findings_comes_from_the_scripts():
    findings = pd.read_csv(ROOT / "outputs" / "key_findings.csv")
    known = set()
    for text in findings.finding:
        known |= numbers(text)
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    section = readme.split("## Key findings")[1].split("## How it was built")[0]
    section = re.sub(r"`[^`]*`", "", section)                       # script names
    unknown = [n for n in numbers(section) if n not in known and n not in {"2024", "2025", "2023", "3"}]
    assert not unknown, unknown


def test_readme_is_short_and_has_the_notice():
    lines = (ROOT / "README.md").read_text(encoding="utf-8").splitlines()
    assert len(lines) < 150
    assert "synthetic" in " ".join(lines[:6]).lower()


def test_no_ai_traces_in_the_project():
    words = ["claude", "anthropic", "openai", "chatgpt", "gpt", "generated by", "co-authored", "as an ai", "ai-generated"]
    skip = {".git", "v1", "__pycache__", ".pytest_cache"}
    hits = []
    for p in ROOT.rglob("*"):
        if not p.is_file() or any(part in skip for part in p.relative_to(ROOT).parts):
            continue
        if p.suffix.lower() in {".csv", ".xlsx", ".png", ".pyc"} or p.name == "test_docs.py":
            continue
        text = p.read_text(encoding="utf-8", errors="ignore").lower()
        hits += [(str(p.relative_to(ROOT)), w) for w in words if w in text]
    assert not hits, hits
